/**
 * Loads the complete construction business demo dataset into localStorage.
 * Dispatches the STORAGE_EVENT so all context and components re-render immediately.
 */
export function loadConstructionDemoData(force = true) {
  try {
    const existingInvoices = getInvoices();
    const existingCustomers = getCustomers();
    const existingBusiness = getBusiness();

    if (!force && existingInvoices.length > 0 && existingCustomers.length > 0 && existingBusiness?.name) {
      return false; // Already has data, don't overwrite unless forced
    }

    saveBusiness(CONSTRUCTION_DEMO_BUSINESS);
    saveSettings(CONSTRUCTION_DEMO_SETTINGS);
    saveCustomers(CONSTRUCTION_DEMO_CUSTOMERS);
    saveProducts(CONSTRUCTION_DEMO_PRODUCTS);
    saveInvoices(CONSTRUCTION_DEMO_INVOICES);
    savePayments(CONSTRUCTION_DEMO_PAYMENTS);

    // Fire generic event to trigger full sync
    window.dispatchEvent(new CustomEvent(STORAGE_EVENT, { detail: { key: null } }));
    return true;
  } catch (err) {
    console.error("Failed to load construction demo data:", err);
    return false;
  }
}

// Automatically bind to window in browser dev mode for easy manual testing
if (typeof window !== "undefined") {
  window.loadConstructionDemoData = loadConstructionDemoData;
  window.CONSTRUCTION_DEMO_DATA = {
    business: CONSTRUCTION_DEMO_BUSINESS,
    settings: CONSTRUCTION_DEMO_SETTINGS,
    customers: CONSTRUCTION_DEMO_CUSTOMERS,
    products: CONSTRUCTION_DEMO_PRODUCTS,
    invoices: CONSTRUCTION_DEMO_INVOICES,
    payments: CONSTRUCTION_DEMO_PAYMENTS,
  };
}

